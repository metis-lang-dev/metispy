"""Sampler-wire golden generator (docs/rewrite/06-sampler-wire.md §5):
python is the referee — canonical program bytes + seeded traces +
final states, reproduced byte-identically by `metisc --sample` (from
the .llp sources) and by cpp sample_run (from the canonical bytes
alone). The corpus is the FULL class: no factored admission here.

Run from the repo root:  python3 cpp/parity/gen_sample_goldens.py"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

from metis.kernel import canonical_bytes, program_key   # noqa: E402
from metis.kernel.refsample import (canonical_events,   # noqa: E402
                                    final_line, run_trace)
from corpus import build_program, parse_manifest        # noqa: E402

from langpath import LANG
MANIFEST = LANG / "corpus/sample_manifest.txt"


def main():
    out = ["# metis sampler-wire goldens — generated by "
           "gen_sample_goldens.py; python is semantic truth"]
    for case in parse_manifest(MANIFEST):
        prog = build_program(case)
        out.append(f"B {case.name} {case.steps} "
                   f"{program_key(prog)}")
        out.append(canonical_bytes(prog).decode().rstrip("\n"))
        out.append(f"E {len(canonical_events(prog))}")
        for seed in range(1, case.seeds + 1):
            trace, final = run_trace(prog, case.steps, seed)
            out.append(f"R {seed} {len(trace)} "
                       + " ".join(str(i) for i in trace)
                       if trace else f"R {seed} 0")
            out.append(final_line(seed, final))
        out.append(".")
    path = LANG / "corpus/goldens/sample_goldens.txt"
    path.write_text("\n".join(out) + "\n")
    r = sum(1 for x in out if x.startswith("R "))
    print(f"wrote {path} ({r} traces)")


if __name__ == "__main__":
    main()
