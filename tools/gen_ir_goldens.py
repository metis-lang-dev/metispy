"""IR golden generator — MANIFEST-DRIVEN (single source:
ocaml/parity/manifest.txt; case builders and named registries in
tests/corpus.py). Python compiles the factor-graph artifact
(kernel/ir.py) and referees every expectation; the C++ interpreter
(metis/ir.hpp) must reproduce them by table ops along the shipped
schedules; the OCaml toolchain must reproduce every symbolic line.

Run from the repo root:  python3 cpp/parity/gen_ir_goldens.py"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

from metis.kernel.factorize import FactoredProgram        # noqa: E402
from metis.kernel.ir import ir_case_lines                 # noqa: E402
from corpus import build_case, parse_manifest             # noqa: E402

from langpath import LANG
MANIFEST = LANG / "corpus/manifest.txt"


def main():
    out = ["# metis IR golden corpus — generated by "
           "gen_ir_goldens.py; python is semantic truth"]
    for case in parse_manifest(MANIFEST):
        prog, hooks = build_case(case)
        fp = FactoredProgram(prog, case.steps, hooks, case.unknowns)
        out += ir_case_lines(case.name, fp, case.queries,
                             likelihoods=case.liks)
    path = LANG / "corpus/goldens/ir_goldens.txt"
    path.write_text("\n".join(out) + "\n")
    m = sum(1 for x in out if x.startswith("M "))
    c = sum(1 for x in out if x == ".")
    print(f"wrote {path} ({c} cases, {m} expectations)")


if __name__ == "__main__":
    main()
