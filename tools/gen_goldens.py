"""Golden generator — python is semantic truth; every expectation in
the golden file comes from the metis python filter. Corpus: the
stage-1 analytic fixtures across horizons + the road mini scenario +
the wheelchair-admitted merge (static-weight programs; port-weighted
programs are exercised through the node's C++ registry, not goldens).

Run from the repo root:  python3 cpp/parity/gen_goldens.py"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
from langpath import LANG  # noqa: E402
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

from metis.kernel import ForwardProjection                    # noqa: E402
from metis.lang import load_llp, weight_policy                # noqa: E402
from metis.domains.road.mini import base_catalog, scenario, \
    wheelchair_pack                                           # noqa: E402
from fixtures import ALL                                      # noqa: E402


def emit_case(out, prog, steps, queries, refs=None, policy=None):
    stage_idx = {s: i for i, s in enumerate(prog.stage_names)}
    out.append(f"N {len(prog.stage_names)} "
               f"{stage_idx[prog.init_stage]}")

    def sections(ev):
        s = ""
        for tag, d in (("c", ev.consume), ("o", ev.produce),
                       ("p", ev.persist)):
            if d:
                s += f" ; {tag}"
                for a, n in sorted(d.items()):
                    s += f" {a} {n}"
        return s

    for i, (kind, stage, ev) in enumerate(prog.events()):
        post = stage_idx[ev.post] if kind == "link" else -1
        wsec = ""
        if refs and refs.get(i):
            factor, args, compl = refs[i]
            wsec = f" ; w {factor} {1 if compl else 0}"
            for a in args:
                wsec += f" {a}"
        out.append(f"E {stage_idx[stage]} {post} {ev.weight:.12g} "
                   f"{ev.name.replace(' ', '_')}{sections(ev)}{wsec}")
    init = " ".join(f"{a} {n}" for a, n in sorted(prog.init.items()))
    out.append(f"I {init}")
    out.append(f"S {steps}")
    pr = ForwardProjection(prog, steps, policy=policy)
    for q in queries:
        vals = " ".join(f"{v:.12g}" for v in pr.final_distribution(q))
        out.append(f"Q {q} {vals}")
    out.append(f"D {pr.p_done():.12g}")
    out.append(f"R {pr.n_reachable()}")
    out.append(".")


ATOMS = {"race": ["wa", "wb", "a"], "ff": ["p", "q", "a"],
         "persist": ["done", "k"], "staged": ["flag", "d", "t"]}


def main():
    out = ["# GENERATED by cpp/parity/gen_goldens.py — do not edit."]
    for name, (make, max_steps) in ALL.items():
        for k in range(1, max_steps + 1):
            emit_case(out, make(), k, ATOMS[name])
    road = base_catalog()
    emit_case(out, road.ground(scenario()), 6,
              ["crash", "wreck(ego)", "wreck(alfa)", "st(ego,l0,c2,v1)"])
    merged = base_catalog().admit(wheelchair_pack())
    emit_case(out, merged.ground(scenario(wc=True)), 8,
              ["crash", "caution(c2)", "wreck(ego)"])

    # port-weighted corpus: sysadmin n=2 through the weight-port path
    # (C++ side resolves via its Registry test bindings)
    doc = load_llp(ROOT / "metis" / "domains" / "sysadmin" /
                   "catalogs" / "sysadmin2.llp")
    ADJ = {"a": ["b"], "b": ["a"]}

    def cpt(args, counts):
        c = args[0]
        if f"rb({c})" in counts:
            return 1.0
        r = sum(1 for y in ADJ[c] if f"prev({y})" in counts)
        return 0.45 + 0.5 * (1 + r) / (1 + len(ADJ[c]))

    bindings = {"cpt": cpt, "rp": lambda a, c: (
        1.0 if f"rb({a[0]})" in c else 0.04)}
    for init, steps, note in (
            ({"m(i0)": 1, "run(a)": 1, "run(b)": 1}, 9, "both-up"),
            ({"m(i0)": 1, "run(a)": 1, "down(b)": 1}, 9, "mixed"),
            ({"m(i0)": 1, "run(a)": 1, "down(b)": 1, "rb(b)": 1}, 9,
             "reboot"),
            ({"m(i0)": 1, "run(a)": 1, "run(b)": 1}, 18, "two-tick")):
        prog = doc.catalog.ground(dict(init))
        pol = weight_policy(prog, doc.ports, bindings)
        # resolved refs per ground event (what weight_policy computes)
        refs = {}
        for i, (kind, stage, ev) in enumerate(prog.events()):
            base = ev.name.split("[", 1)[0]
            ref = doc.ports.weight_refs.get(base)
            if ref is None:
                continue
            tag = ev.name.split("[", 1)[1].rstrip("]")                 if "[" in ev.name else ""
            subst = dict(kv.split("=") for kv in tag.split(","))                  if tag else {}
            refs[i] = (ref.factor,
                       [subst.get(a, a) for a in ref.args],
                       ref.complement)
        emit_case(out, prog, steps, ["run(a)", "run(b)"],
                  refs=refs, policy=pol)
    path = LANG / "corpus/goldens/goldens.txt"
    path.write_text("\n".join(out) + "\n")
    n_checks = sum(1 for l in out if l[:1] in ("Q", "D", "R"))
    print(f"wrote {path} ({out.count('.')} cases, {n_checks} checks)")


if __name__ == "__main__":
    main()
