"""The catalog packages' product wires as metis-lang fixtures (bundle-compiler
s-3985caf6 step 1): metis-lang's ci/check.sh holds `metisc --wire` to them byte
for byte, with no Python and no catalog checkout. For each package this copies
its served sources (the program, its extensions, every include, at their paths
relative to the files' common directory) into LANG/corpus/catalog/<name>/ and
writes the wire metispy's emitter makes of them (metis.kernel.artifact's
served_doc + metis.kernel.wire.emit_artifact: the bundle's ground.wire) to
LANG/corpus/goldens/catalog_wires/<name>.wire; LANG/corpus/catalog/manifest.txt
lists `<name> <program> [<extension>...]`, paths relative to LANG. The
synthetic corpus/wire_ports.llp (authored in metis-lang: every port kind, a
weight's complement, doubles whose shortest text is not trivial) gets its wire
the same way.

The wires and the manifest carry the header line of the fixture rule:

  # GENERATED by metispy <commit> tools/gen_catalog_wires.py sha256:<hex> — do not edit

  python tools/gen_catalog_wires.py [LANG]          write
  python tools/gen_catalog_wires.py --check [LANG]  regenerate and diff (CI)

--check compares every line but the commit (gen_smoke_fixtures' rule), the
copied sources byte for byte. The catalog is metis_catalog (installed, or
$METIS_CATALOG, else the sibling checkout)."""

import argparse
import difflib
import hashlib
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from langpath import LANG  # noqa: E402
from gen_smoke_fixtures import commit, sans_commit  # noqa: E402

GEN = "tools/gen_catalog_wires.py"
PACKAGES = ["dog", "plant", "kitchen", "kitchen_shared"]
SYNTHETIC = {"wire_ports": "corpus/wire_ports.llp"}   # relative to LANG
INCLUDE = re.compile(r'^\s*include\s+"([^"]+)"\s*\.', re.M)


def sources(program: Path, extensions) -> list:
    """The served files and their includes, transitively, in order."""
    seen, out = set(), []

    def visit(p: Path):
        p = p.resolve()
        if p in seen:
            return
        seen.add(p)
        out.append(p)
        for inc in INCLUDE.findall(p.read_text()):
            visit(p.parent / inc)
    for p in [program, *extensions]:
        visit(Path(p))
    return out


def wire(program: Path, extensions) -> str:
    from metis.kernel.artifact import served_doc
    from metis.kernel.wire import emit_artifact
    doc, case, _ = served_doc(program, extensions)
    prog = doc.catalog.ground(dict(case["init"]))
    return emit_artifact(doc, prog, case["steps"])


def generate(lang: Path) -> dict:
    """{path relative to LANG: text} — sources, wires, the manifest."""
    from metis.kernel.artifact import resolve
    rev = commit()
    digest = hashlib.sha256((ROOT / GEN).read_bytes()).hexdigest()
    header = f"# GENERATED by metispy {rev} {GEN} sha256:{digest} — do not edit\n"
    files, rows = {}, []
    for name in PACKAGES:
        program, extensions, _ = resolve(name)
        srcs = sources(program, extensions)
        base = Path(os.path.commonpath([p.parent for p in srcs]))
        dest = Path("corpus/catalog") / name
        for p in srcs:
            files[str(dest / p.relative_to(base))] = p.read_text()
        rel = [str(dest / Path(p).resolve().relative_to(base))
               for p in [program, *extensions]]
        rows.append(" ".join([name, *rel]))
        files[f"corpus/goldens/catalog_wires/{name}.wire"] = \
            header + wire(program, extensions)
    for name, rel in SYNTHETIC.items():
        rows.append(f"{name} {rel}")
        files[f"corpus/goldens/catalog_wires/{name}.wire"] = \
            header + wire(lang / rel, [])
    files["corpus/catalog/manifest.txt"] = (
        header + "# <name> <program> [<extension>...] — paths relative to the "
        "metis-lang root; ci/check.sh gate 12 runs metisc --wire on each\n"
        + "".join(r + "\n" for r in rows))
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("lang", nargs="?", type=Path, default=LANG)
    ap.add_argument("--check", action="store_true",
                    help="regenerate and diff against LANG; exit 1 on drift")
    a = ap.parse_args()
    files = generate(a.lang)
    if not a.check:
        wrote = 0
        for rel, text in files.items():
            path = a.lang / rel
            if path.exists() and sans_commit(path.read_text()) == \
                    sans_commit(text):
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            wrote += 1
        print(f"wrote {wrote} of {len(files)} files under {a.lang}/corpus "
              "(the rest unchanged)")
        return 0
    drift = 0
    for rel, text in files.items():
        path = a.lang / rel
        have = path.read_text() if path.exists() else ""
        diff = list(difflib.unified_diff(sans_commit(have), sans_commit(text),
                                         str(path), f"regenerated {rel}"))
        if diff:
            drift += 1
            sys.stdout.writelines(diff)
    print(f"catalog wires: {len(files) - drift}/{len(files)} clean in "
          f"{a.lang}/corpus")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
