import json
import os


def instance_text(name, base, types=None, facts=(), init=(), directives=None, header=None, provenance=None):
    """The instance's text: `% header`, `catalog NAME 1.`, `provenance text "…" "date".`, the base's
    `include`, one `type T {members}.` per type (in the order given), a blank line, each fact as
    `fact.`, a blank line, `#init ATOM 1` per start atom, then each directive as `#KEY VALUE`."""
    lines = []
    for h in ([header] if isinstance(header, str) else list(header or [])):
        lines.append("% " + h)
    lines.append("catalog %s 1." % name)
    if provenance:
        what, date = provenance
        lines.append("provenance text %s %s." % (json.dumps(what), json.dumps(date)))
    lines.append('include "%s".' % base)
    for t, members in (types or {}).items():
        lines.append("type %s {%s}." % (t, " ".join(members)))
    lines.append("")
    lines += [f + "." for f in facts] + [""]
    lines += ["#init %s 1" % a for a in init]
    lines += ["#%s %s" % (k, v) for k, v in (directives or {}).items()]
    return "\n".join(lines) + "\n"


def write_instance(out_dir, name, text, file=None):
    """The instance as a package directory: out_dir/NAME/FILE (default NAME.llp). → its path."""
    pkg = os.path.join(out_dir, name)
    os.makedirs(pkg, exist_ok=True)
    path = os.path.join(pkg, file or name + ".llp")
    with open(path, "w") as f:
        f.write(text)
    return path
