"""metis.catalog.instance (metis-packages s-65778b98): an instance program from a lifted base and fact
tables. The reference is metis-worlds' alfworld/world/gen_hier.py generate_director: with metis-worlds beside
this checkout (or $METIS_ALF_WORLD), the director it writes is byte for byte instance_text's."""
import importlib.util
import os
from pathlib import Path

import pytest

from metis.catalog.instance import instance_text, write_instance


def test_the_instances_text():
    t = instance_text("toy_1", "../toy_domain.llp", types={"thing": ["a", "b"]}, facts=["near(a, b)"],
                      init=["at(a)", "fresh"], directives={"steps": 6, "seeds": 1}, header="toy_1 — a toy.",
                      provenance=("generated: a toy", "2026-10-22"))
    assert t == ('% toy_1 — a toy.\ncatalog toy_1 1.\nprovenance text "generated: a toy" "2026-10-22".\n'
                 'include "../toy_domain.llp".\ntype thing {a b}.\n\nnear(a, b).\n\n#init at(a) 1\n#init fresh 1\n'
                 '#steps 6\n#seeds 1\n')


def test_write_instance_makes_its_package(tmp_path):
    p = write_instance(tmp_path, "toy_1", "catalog toy_1 1.\n", file="toy.llp")
    assert p == os.path.join(tmp_path, "toy_1", "toy.llp") and Path(p).read_text() == "catalog toy_1 1.\n"
    assert write_instance(tmp_path, "toy_2", "x\n").endswith(os.path.join("toy_2", "toy_2.llp"))


def _gen_hier():
    world = os.environ.get("METIS_ALF_WORLD") or str(Path(__file__).resolve().parents[3] / "metis-worlds" / "alfworld" / "world")
    p = Path(world) / "gen_hier.py"
    if not p.is_file():
        return None
    import sys
    sys.path.insert(0, str(p.parent))
    try:
        spec = importlib.util.spec_from_file_location("gen_hier_ref", p)
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        return m
    except Exception:  # noqa: BLE001 — the world's own imports missing: no reference here
        return None
    finally:
        sys.path.remove(str(p.parent))


def test_the_director_is_gen_hiers_byte_for_byte(tmp_path):
    g = _gen_hier()
    if g is None:
        pytest.skip("no metis-worlds beside this checkout ($METIS_ALF_WORLD)")
    init = g.director_start() + ["arrival(goto(loc3))"]
    ref = Path(g.generate_director(str(tmp_path / "ref"), 3, init)).read_text()
    kinds, facts = g.director_facts()
    ours = instance_text("director_3", "../../director_domain.llp", types={"domain": list(g.SPECS), "kind": kinds},
                         facts=facts, init=init, directives={"steps": 6, "seeds": 1},
                         header="director_3 — the director's beat 3 over the ALFWorld hierarchy (generated by world/gen_hier.py).",
                         provenance=("generated: the director over nav/access/grasp/place/task, beat 3", "2026-10-22"))
    assert ours == ref
